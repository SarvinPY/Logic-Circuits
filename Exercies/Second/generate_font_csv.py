def byte_to_dots(byte_val: int) -> str:
    return ''.join('#' if (byte_val >> (7-b)) & 1 else '.' for b in range(8))

def write_csv(font: dict, order: list, path: str):
    with open(path, 'w', encoding='utf-8') as f:
        f.write('INDEX,NAME,HEX_BYTES,ROW0,ROW1,ROW2,ROW3,ROW4,ROW5,ROW6,ROW7\n')
        for idx, name in enumerate(order):
            bm = font[name]
            hex_bytes = ' '.join(f'{b:02X}' for b in bm)
            rows = ','.join(byte_to_dots(b) for b in bm)
            f.write(f'{idx},{name},{hex_bytes},{rows}\n')
    print(f'✅ CSV written → {path}  ({len(order)} characters)')

